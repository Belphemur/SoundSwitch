/** Sends the thank-you email via the Postmark API. */
export async function sendPostmarkThankYou(
  env: Env,
  payer: { firstName: string; lastName: string; email: string },
  amount: string,
  currency: string,
): Promise<void> {
  const siteHost = env.SITE_HOSTNAME || "https://soundswitch.aaflalo.me";
  const logoUrl = `${siteHost}/logo-icon.svg`;
  const html = buildThankYouHtml({ ...payer, amount, currency, logoUrl });
  const from = env.POSTMARK_FROM;
  if (!from) {
    throw new Error("POSTMARK_FROM secret is not configured");
  }

  const res = await fetch(POSTMARK_API, {
    method: "POST",
    headers: {
      "content-type": "application/json",
      accept: "application/json",
      "X-Postmark-Server-Token": env.POSTMARK_SERVER_TOKEN ?? "",
    },
    body: JSON.stringify({
      From: from,
      To: payer.email,
      Subject: "Thank you for supporting SoundSwitch!",
      HtmlBody: html,
      MessageStream: "outbound",
    }),
  });
  if (!res.ok) {
    const text = await res.text();
    throw new Error(`Postmark send failed: ${res.status} ${text}`);
  }
}

/**
 * Worker handler for `POST /api/paypal-ipn`.
 * Verifies the IPN with PayPal, then sends the thank-you email. Never
 * acknowledges a non-verified IPN with 2xx (returns 500 so PayPal retries);
 * acknowledges with 200 only after a successful send. A Postmark failure also
 * returns 500 so PayPal retries (retry-safe). Replayed IPNs are de-duplicated by
 * txn_id via the required `IPN_DEDUPE` KV, so the donor never gets a duplicate.
 */
export async function handlePayPalIpn(
  request: Request,
  env: Env,
  _ctx: ExecutionContext,
): Promise<Response> {
  if (request.method !== "POST") {
    return new Response("Method Not Allowed", { status: 405 });
  }

  if (!env.POSTMARK_SERVER_TOKEN || !env.POSTMARK_FROM) {
    return new Response(
      JSON.stringify({ error: "Postmark secrets are not configured" }),
      {
        status: 503,
        headers: { "content-type": "application/json; charset=utf-8" },
      },
    );
  }

  // Dedupe KV is mandatory: replays must never send a duplicate email. If it's
  // unbound the worker can't guarantee idempotency, so refuse to process.
  if (!env.IPN_DEDUPE) {
    return new Response(
      JSON.stringify({ error: "IPN_DEDUPE KV binding is not configured" }),
      {
        status: 503,
        headers: { "content-type": "application/json; charset=utf-8" },
      },
    );
  }

  const rawBody = await request.text();

  // Apply the optional merchant-email guard here (parseIpn skips it by default).
  if (env.PAYPAL_MERCHANT_EMAIL) {
    const receiver = new URLSearchParams(rawBody).get("receiver_email") ||
      new URLSearchParams(rawBody).get("business") || "";
    if (
      receiver &&
      receiver.toLowerCase() !== env.PAYPAL_MERCHANT_EMAIL.toLowerCase()
    ) {
      return new Response(JSON.stringify({ received: true, ignored: true }), {
        status: 200,
        headers: { "content-type": "application/json; charset=utf-8" },
      });
    }
  }

  const result = await verifyIpn(rawBody, env);
  if (!result.verified) {
    // Never acknowledge a non-verified IPN with 2xx: PayPal retries notifications
    // that get a non-2xx response. A verification failure (network, PayPal 5xx,
    // worker misconfiguration, or a message PayPal rejects) must be retried so we
    // never silently drop a real donation. (Genuine spoofs will keep retrying until
    // PayPal gives up after ~4 days — an acceptable cost versus losing a real one.)
    console.error(`IPN not verified (${result.reason}) — returning 500 so PayPal retries`);
    return new Response(JSON.stringify({ received: false, reason: result.reason }), {
      status: 500,
      headers: { "content-type": "application/json; charset=utf-8" },
    });
  }

  const donation = parseIpn(rawBody);
  if (donation && donation.email) {
    // Reject IPNs that weren't generated by our donate buttons (no SoundSwitch- custom).
    if (!isOurCustom(donation.custom)) {
      return new Response(JSON.stringify({ received: true, ignored: true }), {
        status: 200,
        headers: { "content-type": "application/json; charset=utf-8" },
      });
    }

    // Idempotent, retry-safe claim: register the txn_id BEFORE sending so a
    // Postmark-then-KV-failure or a concurrent replay can't send a duplicate.
    // The claim uses a unique nonce marker; if a key already exists (real
    // replay or in-flight duplicate) we skip sending and ack 200.
    if (donation.txnId) {
      const CLAIM = "claimed";
      const existing = await env.IPN_DEDUPE.get(donation.txnId);
      if (existing) {
        return new Response(JSON.stringify({ received: true, duplicate: true }), {
          status: 200,
          headers: { "content-type": "application/json; charset=utf-8" },
        });
      }
      await env.IPN_DEDUPE.put(donation.txnId, CLAIM, {
        expirationTtl: 60 * 60 * 24 * 7,
      });
    }

    try {
      await sendPostmarkThankYou(env, donation, donation.amount, donation.currency);
    } catch (err) {
      // Roll back the claim so PayPal's retry can attempt delivery again, then
      // return 500 to force the retry. (If the rollback itself fails we still
      // 500 — the 7-day TTL bounds any eventual stale key.)
      if (donation.txnId) {
        try {
          await env.IPN_DEDUPE.delete(donation.txnId);
        } catch {
          /* best-effort */
        }
      }
      console.error("donation thank-you email failed", err);
      return new Response(JSON.stringify({ received: false, email_failed: true }), {
        status: 500,
        headers: { "content-type": "application/json; charset=utf-8" },
      });
    }
  }

  return new Response(JSON.stringify({ received: true }), {
    status: 200,
    headers: { "content-type": "application/json; charset=utf-8" },
  });
}
