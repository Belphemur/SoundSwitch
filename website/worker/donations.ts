import type { Env } from "./types";

const POSTMARK_API = "https://api.postmarkapp.com/email";
const PAYPAL_IPN_LIVE = "https://ipnpb.paypal.com/cgi-bin/webscr";
const PAYPAL_IPN_SANDBOX = "https://ipnpb.sandbox.paypal.com/cgi-bin/webscr";

interface IpnDonation {
  firstName: string;
  lastName: string;
  email: string;
  amount: string;
  currency: string;
  txnId: string;
  custom: string;
}

/**
 * Parses a PayPal IPN POST body (form-urlencoded) into a donation.
 * Returns null unless `payment_status` is `Completed` (so pending/refunded
 * IPNs don't trigger a thank-you). All donor fields are optional — PayPal may
 * omit name/email for some guest checkouts, in which case we fall back in the
 * email builder.
 */
function parseIpn(rawBody: string): IpnDonation | null {
  const params = new URLSearchParams(rawBody);
  if (params.get("payment_status") !== "Completed") return null;

  return {
    firstName: params.get("first_name") ?? "",
    lastName: params.get("last_name") ?? "",
    email: params.get("payer_email") ?? "",
    amount: params.get("mc_gross") ?? "0.00",
    currency: params.get("mc_currency") ?? "USD",
    txnId: params.get("txn_id") ?? "",
    custom: params.get("custom") ?? "",
  };
}

// The donor-side `custom` value we set on every donate link (HomeHero.vue).
// Requiring it rejects stray/forged IPNs that weren't generated by our buttons.
const CUSTOM_PREFIX = "SoundSwitch-";

/** True if the IPN carries a `custom` value we recognize. */
function isOurCustom(custom: string): boolean {
  return custom.startsWith(CUSTOM_PREFIX);
}

// `env` is passed at call time; this tiny indirection keeps parseIpn pure-ish.
function Env_merchant(_env: Env): string | undefined {
  return undefined; // merchant check is applied in the handler via env directly
}

/**
 * Verifies a PayPal IPN by echoing it back to PayPal with `cmd=_notify-validate`.
 * PayPal responds with the body `VERIFIED` (or `INVALID`). This is the standard
 * IPN verification handshake and works on a Personal PayPal account — no Business
 * account or REST app required.
 */
/**
 * Verifies a PayPal IPN by echoing it back to PayPal with `cmd=_notify-validate`.
 * PayPal responds with the body `VERIFIED` (or `INVALID`). This is the standard
 * IPN verification handshake and works on a Personal PayPal account — no Business
 * account or REST app required.
 *
 * Returns `verified: false` with a `reason`:
 * - "invalid": PayPal itself said the message is not a valid IPN.
 * - "error":  the verification request failed (network/timeout/PayPal 5xx) or the
 *             worker is misconfigured. Treat as retryable.
 */
export type IpnVerifyResult =
  | { verified: true }
  | { verified: false; reason: "invalid" | "error" };

export async function verifyIpn(rawBody: string, env: Env): Promise<IpnVerifyResult> {
  const mode = env.PAYPAL_IPN_MODE;
  if (mode !== "sandbox" && mode !== "live" && mode !== undefined && mode !== "") {
    console.error(`Invalid PAYPAL_IPN_MODE: ${mode}`);
    return { verified: false, reason: "error" };
  }
  const endpoint = mode === "sandbox" ? PAYPAL_IPN_SANDBOX : PAYPAL_IPN_LIVE;
  const body = `cmd=_notify-validate&${rawBody}`;

  try {
    const res = await fetch(endpoint, {
      method: "POST",
      headers: { "content-type": "application/x-www-form-urlencoded" },
      body,
    });
    if (!res.ok) {
      console.error(`PayPal IPN verification request failed: HTTP ${res.status}`);
      return { verified: false, reason: "error" };
    }
    const text = (await res.text()).trim();
    if (text === "VERIFIED") return { verified: true };
    console.warn(`PayPal IPN verification returned "${text}"`);
    return { verified: false, reason: text === "INVALID" ? "invalid" : "error" };
  } catch (err) {
    console.error("PayPal IPN verification request threw", err);
    return { verified: false, reason: "error" };
  }
}

